package main

import (
	"bufio"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	// newPackageMinimum is the coverage a package without a baseline entry must reach.
	newPackageMinimum = 80.0
	// tolerance absorbs rounding between the stored baseline and the measured value.
	tolerance = 0.5
)

// measured reports whether a package takes part in the ratchet. Generated mock packages and
// internal tooling are excluded.
func measured(importPath string) bool {
	if strings.Contains(importPath, "/internal/") {
		return false
	}
	return !strings.HasSuffix(path.Base(importPath), "mock")
}

// parseProfile aggregates a Go coverage profile into statement coverage percent per package.
func parseProfile(r io.Reader) (map[string]float64, error) {
	total := map[string]int{}
	covered := map[string]int{}
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "mode:") || strings.TrimSpace(line) == "" {
			continue
		}
		file, rest, ok := strings.Cut(line, ":")
		if !ok {
			return nil, fmt.Errorf("malformed profile line %q", line)
		}
		fields := strings.Fields(rest)
		if len(fields) != 3 {
			return nil, fmt.Errorf("malformed profile line %q", line)
		}
		stmts, err1 := strconv.Atoi(fields[1])
		count, err2 := strconv.Atoi(fields[2])
		if err1 != nil || err2 != nil {
			return nil, fmt.Errorf("malformed profile line %q", line)
		}
		if strings.HasPrefix(path.Base(file), "mock_") {
			continue
		}
		pkg := path.Dir(file)
		if !measured(pkg) {
			continue
		}
		total[pkg] += stmts
		if count > 0 {
			covered[pkg] += stmts
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	out := make(map[string]float64, len(total))
	for pkg, n := range total {
		if n == 0 {
			out[pkg] = 100
			continue
		}
		out[pkg] = float64(covered[pkg]) * 100 / float64(n)
	}
	return out, nil
}

// evaluate compares current coverage with the baseline and returns human-readable problems.
func evaluate(current, baseline map[string]float64) []string {
	var problems []string
	for _, pkg := range sortedKeys(current) {
		cov := current[pkg]
		base, known := baseline[pkg]
		switch {
		case !known && cov < newPackageMinimum:
			problems = append(problems, fmt.Sprintf("%s: new package at %.1f%%, needs at least %.0f%%", pkg, cov, newPackageMinimum))
		case known && cov+tolerance < base:
			problems = append(problems, fmt.Sprintf("%s: coverage dropped to %.1f%% (baseline %.1f%%)", pkg, cov, base))
		}
	}
	return problems
}

func readBaseline(file string) (map[string]float64, error) {
	f, err := os.Open(file) //nolint:gosec // path comes from the developer's command line
	if err != nil {
		return nil, fmt.Errorf("open baseline: %w (create it with -update)", err)
	}
	defer func() { _ = f.Close() }()
	out := map[string]float64{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			return nil, fmt.Errorf("malformed baseline line %q", line)
		}
		v, err := strconv.ParseFloat(fields[1], 64)
		if err != nil {
			return nil, fmt.Errorf("malformed baseline line %q: %w", line, err)
		}
		out[fields[0]] = v
	}
	return out, sc.Err()
}

func writeBaseline(file string, current map[string]float64) error {
	var b strings.Builder
	b.WriteString("# Per-package statement coverage baseline (TEST-3). Generated by internal/tools/covercheck -update.\n")
	b.WriteString("# Coverage may not drop below these values; raise them as tests are added.\n")
	for _, pkg := range sortedKeys(current) {
		fmt.Fprintf(&b, "%s %.1f\n", pkg, current[pkg])
	}
	return os.WriteFile(file, []byte(b.String()), 0o644) //nolint:gosec // baseline is a tracked, non-secret file
}

func sortedKeys(m map[string]float64) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// hasStatements reports whether any of files (in dir) declares a function or method with a body.
// Interface-only packages have nothing to cover and must not be counted as 0%.
func hasStatements(dir string, files []string) bool {
	fset := token.NewFileSet()
	for _, name := range files {
		if strings.HasPrefix(name, "mock_") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return true // be strict when a file cannot be parsed
		}
		for _, d := range f.Decls {
			if fn, ok := d.(*ast.FuncDecl); ok && fn.Body != nil && len(fn.Body.List) > 0 {
				return true
			}
		}
	}
	return false
}
